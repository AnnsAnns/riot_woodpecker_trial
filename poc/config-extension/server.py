#!/usr/bin/env python3
"""
Woodpecker configuration extension: Murdock-compatible job generation.

The dispatcher (`dispatch.py`) discovers the real `.murdock get_jobs` set and
then starts **one Woodpecker pipeline per Murdock job**, passing the job list in
the `MURDOCK_BATCH` variable. This extension expands that variable into one
workflow per build/test job, so the Woodpecker pipeline page shows the same set
of builds/tests that murfrog shows for a Murdock job.

It also supports single jobs (`MURDOCK_KIND`, used by nothing by default) and
Murdock's gates (skip keywords, `CI: ready for build`, push-branch filter).

Offline use:

    python3 server.py --request sample-request.json --out out/
"""

from __future__ import annotations

import argparse
import base64
import json
import os
import re
import sys
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

HERE = os.path.dirname(os.path.abspath(__file__))
BOOTSTRAP_IMAGE = os.environ.get("POC_BOOTSTRAP_IMAGE", "riotbuild-cached:poc")
JOB_IMAGE = os.environ.get("POC_JOB_IMAGE", "riotbuild-cached:poc")

# Murdock gates (RIOT/.murdock.yml + murdock config defaults)
READY_LABEL = os.environ.get("POC_READY_LABEL", "CI: ready for build")
SKIP_KEYWORDS = [k for k in os.environ.get(
    "POC_SKIP_KEYWORDS", "ci_skip,murdock_skip,[ci skip]").split(",") if k]
PUSH_BRANCHES = [b for b in os.environ.get(
    "POC_PUSH_BRANCHES", "^staging$,^trying$,^gh-readonly-queue/").split(",") if b]
PUSH_TAGS = [t for t in os.environ.get("POC_PUSH_TAGS", "").split(",") if t]

EVENTS = ["push", "pull_request", "pull_request_metadata", "pull_request_closed",
          "manual", "tag"]

# Runs inside the job container: checkout the right ref, install the
# dwq-localjob shim, then run the real `.murdock` subcommand. Kept as a script
# so no `${...}` appears in the YAML (Woodpecker substitutes those before
# parsing, which can break YAML).
JOB_SH = r"""#!/bin/sh
set -e
export GIT_TERMINAL_PROMPT=0
# Fast, cache-shared checkout (Murdock's git-cache): objects live in
# GIT_CACHE_DIR (/cache/.gitcache) and are shared via git alternates, so the
# thousandth clone is as cheap as the first.
if [ -n "${CI_REPO_CLONE_URL:-}" ] && [ -n "${MURDOCK_COMMIT:-}" ]; then
    git-cache clone "${CI_REPO_CLONE_URL}" . --commit "${MURDOCK_COMMIT}"
elif [ -n "${MURDOCK_REF:-}" ]; then
    git fetch --no-tags origin "${MURDOCK_REF}" 2>/dev/null && git checkout -q FETCH_HEAD 2>/dev/null || true
fi
cat > /usr/local/bin/dwq-localjob <<'SH'
#!/bin/sh
while [ $# -gt 0 ] && [ "$1" != "--" ]; do shift; done
[ "$1" = "--" ] && shift
exec "$@"
SH
chmod +x /usr/local/bin/dwq-localjob
case "${MURDOCK_KIND}" in
    compile) exec ./.murdock compile "${MURDOCK_APP}" "${MURDOCK_BOARD}:${MURDOCK_TOOLCHAIN}" ;;
    test)    exec ./.murdock run_test "${MURDOCK_APP}" "${MURDOCK_BOARD}:${MURDOCK_TOOLCHAIN}" ;;
    static)  exec ./.murdock static_tests ;;
    *) echo "unknown MURDOCK_KIND=${MURDOCK_KIND}" >&2; exit 1 ;;
esac
"""


def log(*a):
    print(*a, file=sys.stderr, flush=True)


def b64(text: str) -> str:
    return base64.b64encode(text.encode()).decode()


def _read_dispatch():
    with open(os.path.join(HERE, "dispatch.py")) as f:
        return f.read()


# --------------------------------------------------------------------------
# Workflow generation
# --------------------------------------------------------------------------

def bootstrap_workflow() -> str:
    script = b64(_read_dispatch())
    return "\n".join([
        "# generated by murdock-compat config extension: bootstrap dispatcher",
        "when:",
        f"  - event: [{', '.join(EVENTS)}]",
        # no Woodpecker clone; dispatch.py does a git-cache checkout
        "skip_clone: true",
        "steps:",
        "  - name: discover-and-dispatch",
        f"    image: {BOOTSTRAP_IMAGE}",
        # host networking: the step talks to localhost:8000/3000
        "    network_mode: host",
        "    environment:",
        '      WOODPECKER_SERVER_INTERNAL: "http://localhost:8000"',
        '      GIT_CACHE_DIR: "/cache/.gitcache"',
        f'      POC_MERGE_TTL: "{os.environ.get("POC_MERGE_TTL", "3600")}"',
        f'      POC_DISCOVERY_JOBS: "{os.environ.get("POC_DISCOVERY_JOBS", "8")}"',
        f'      POC_MAX_DISPATCH: "{os.environ.get("POC_MAX_DISPATCH", "0")}"',
        "      WP_TOKEN:",
        "        from_secret: wp_token",
        "      FORGEJO_TOKEN:",
        "        from_secret: forgejo_token",
        "    commands:",
        f"      - 'echo \"{script}\" | base64 -d > /tmp/dispatch.py'",
        "      - 'python3 /tmp/dispatch.py'",
    ]) + "\n"


def gated_workflow(reason: str) -> str:
    safe = reason.replace("'", "").replace(":", "-")
    return "\n".join([
        "# generated by murdock-compat config extension: gated (no build)",
        "when:",
        f"  - event: [{', '.join(EVENTS)}]",
        # the gate is a pure `echo`; no checkout and no network needed.
        # (step-level `network_mode` is supported by the docker backend but is
        # missing from Woodpecker's linter schema, which warns about it.)
        "skip_clone: true",
        "steps:",
        "  - name: gated",
        "    image: alpine:3.20",
        "    commands:",
        f"      - 'echo \"murdock gate - {safe}\"'",
    ]) + "\n"


def job_name(job: dict) -> str:
    kind = job.get("kind", "compile")
    if kind == "static":
        return "static tests"
    # Woodpecker uses the basename of the config name as the workflow name, so
    # avoid '/' (replace it) to keep the full application path visible.
    app = job.get("app", "").replace("/", "_")
    base = f'{app} {job.get("board", "")}:{job.get("toolchain", "")}'
    return f"test {base}" if kind == "test" else base


def job_workflow(job: dict, common: dict) -> str:
    """One workflow for a single Murdock build/test job (used inside a batch)."""
    script = b64(JOB_SH)
    kind = job.get("kind", "compile")
    app = job.get("app", "")
    board = job.get("board", "")
    toolchain = job.get("toolchain", "")

    lines = [
        f"# murdock {kind} job: {job_name(job)}",
        "when:",
        f"  - event: [{', '.join(EVENTS)}]",
        # no Woodpecker clone step; job.sh does a git-cache checkout instead
        "skip_clone: true",
        "steps:",
        "  - name: " + ("static-tests" if kind == "static" else kind),
        f"    image: {JOB_IMAGE}",
        # host networking: git-cache clones from localhost:3000, ccache/test
        # caches use localhost:6379
        "    network_mode: host",
        "    environment:",
        f'      MURDOCK_KIND: "{kind}"',
        f'      MURDOCK_APP: "{app}"',
        f'      MURDOCK_BOARD: "{board}"',
        f'      MURDOCK_TOOLCHAIN: "{toolchain}"',
        f'      MURDOCK_REF: "{common.get("MURDOCK_REF", "")}"',
        f'      MURDOCK_COMMIT: "{common.get("MURDOCK_COMMIT", "")}"',
        f'      BOARD: "{board}"',
        f'      TOOLCHAIN: "{toolchain}"',
        '      RIOT_CI_BUILD: "1"',
        f'      JOBS: "{common.get("MURDOCK_JOBS", "4")}"',
        f'      ENABLE_TEST_CACHE: "{common.get("MURDOCK_ENABLE_TEST_CACHE", "1")}"',
        f'      STATIC_TESTS: "{common.get("MURDOCK_STATIC_TESTS", "0")}"',
        # shared caches (Murdock's redis-ccache + /cache)
        '      MURDOCK_REDIS_HOST: "localhost"',
        '      CCACHE: "ccache"',
        '      CCACHE_DIR: "/cache/.ccache"',
        '      CCACHE_REMOTE_ONLY: "1"',
        '      CCACHE_REMOTE_STORAGE: "redis://localhost:6379"',
        '      DLCACHE_DIR: "/cache/.dlcache"',
        '      GIT_CACHE_DIR: "/cache/.gitcache"',
        '      RUN_TESTS: "0"',
        "    commands:",
        f"      - 'echo \"{script}\" | base64 -d > /tmp/job.sh'",
        "      - 'sh /tmp/job.sh'",
    ]
    if kind == "test":
        # route hardware test jobs to an agent with the board attached
        lines += ["labels:", f'  board: "{board}"']
    return "\n".join(lines) + "\n"


def handle_ref(ref: str, rules: list[str]) -> bool:
    if not rules:
        return False
    return "*" in rules or ref in rules or any(re.match(r, ref) for r in rules)


def _jobs_from_variables(variables: dict) -> list[dict] | None:
    """Return the list of jobs for a dispatched pipeline, or None."""
    if "MURDOCK_BATCH" in variables:
        try:
            jobs = json.loads(variables["MURDOCK_BATCH"])
            if isinstance(jobs, list):
                return jobs
        except json.JSONDecodeError:
            log("[extension] invalid MURDOCK_BATCH JSON")
    if "MURDOCK_KIND" in variables:
        return [{"kind": variables["MURDOCK_KIND"],
                 "app": variables.get("MURDOCK_APP", ""),
                 "board": variables.get("MURDOCK_BOARD", ""),
                 "toolchain": variables.get("MURDOCK_TOOLCHAIN", "")}]
    return None


def build_response(request: dict) -> dict:
    if os.environ.get("POC_LOG_REQUEST"):
        log("[request] " + json.dumps(request))
    pipeline = request.get("pipeline", {})
    variables = pipeline.get("variables") or {}

    jobs = _jobs_from_variables(variables)
    if jobs is not None:
        configs = [{"name": job_name(j), "data": job_workflow(j, variables)}
                   for j in jobs]
        log(f"[extension] pipeline with {len(configs)} workflow(s): "
            + ", ".join(c["name"] for c in configs[:4])
            + (" ..." if len(configs) > 4 else ""))
        return {"configs": configs}

    # --- Murdock gates for normal triggers -------------------------------
    event = pipeline.get("event")
    message = pipeline.get("message", "") or ""
    for kw in SKIP_KEYWORDS:
        if kw and kw in message:
            log(f"[extension] skip keyword {kw!r}")
            return _gated(f"skip keyword {kw}")
    if event == "pull_request_closed":
        return _gated("PR closed")
    if event == "pull_request_metadata":
        return _gated("PR metadata change")
    if event == "pull_request":
        labels = pipeline.get("pr_labels") or []
        if READY_LABEL not in labels:
            log(f"[extension] ready label {READY_LABEL!r} not set")
            return _gated(f"waiting for label {READY_LABEL}")
    elif event == "push":
        ref = pipeline.get("ref", "") or ""
        if ref.startswith("refs/tags/"):
            if not handle_ref(ref[len("refs/tags/"):], PUSH_TAGS):
                return _gated(f"tag {ref} not enabled")
        elif ref.startswith("refs/heads/"):
            if not handle_ref(ref[len("refs/heads/"):], PUSH_BRANCHES):
                log(f"[extension] branch {ref} not in push.branches")
                return _gated(f"branch {ref} not enabled")

    cfg = bootstrap_workflow()
    log("[extension] bootstrap dispatcher config")
    return {"configs": [{"name": "murdock-bootstrap", "data": cfg}]}


def _gated(reason: str) -> dict:
    return {"configs": [{"name": "murdock-gated", "data": gated_workflow(reason)}]}


# --------------------------------------------------------------------------
# HTTP server
# --------------------------------------------------------------------------

class Handler(BaseHTTPRequestHandler):
    def log_message(self, fmt, *args):
        log("[http]", fmt % args)

    def _send(self, code, payload=None):
        body = b"" if payload is None else json.dumps(payload).encode()
        self.send_response(code)
        if payload is not None:
            self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        if body:
            self.wfile.write(body)

    def do_GET(self):
        if self.path in ("/health", "/"):
            self._send(200, {"status": "ok"})
        else:
            self._send(404, {"error": "not found"})

    def do_POST(self):
        if self.path.rstrip("/") not in ("/config", ""):
            self._send(404, {"error": "not found"})
            return
        length = int(self.headers.get("Content-Length", "0"))
        raw = self.rfile.read(length) if length else b"{}"
        try:
            request = json.loads(raw or b"{}")
            self._send(200, build_response(request))
        except Exception as exc:  # noqa: BLE001
            log(f"[http] error: {exc!r}")
            self._send(500, {"error": str(exc)})


def serve(host, port):
    log(f"[extension] serving on {host}:{port} (bootstrap={BOOTSTRAP_IMAGE}, job={JOB_IMAGE})")
    ThreadingHTTPServer((host, port), Handler).serve_forever()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--serve", action="store_true")
    parser.add_argument("--host", default="0.0.0.0")
    parser.add_argument("--port", type=int, default=8000)
    parser.add_argument("--request", help="request JSON file (offline mode)")
    parser.add_argument("--out", help="directory to write generated configs to")
    args = parser.parse_args()

    if args.serve:
        serve(args.host, args.port)
        return
    if not args.request:
        parser.error("either --serve or --request is required")

    with open(args.request) as f:
        request = json.load(f)
    response = build_response(request)
    print(json.dumps(response, indent=2))
    if args.out:
        os.makedirs(args.out, exist_ok=True)
        for i, cfg in enumerate(response["configs"]):
            safe = re.sub(r"[^A-Za-z0-9._-]+", "_", cfg["name"]).strip("_")
            path = os.path.join(args.out, f"{i:03d}_{safe}.yaml")
            with open(path, "w") as f:
                f.write(cfg["data"])
            log(f"[cli] wrote {path}")


if __name__ == "__main__":
    main()
